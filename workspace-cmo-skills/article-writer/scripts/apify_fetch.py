#!/usr/bin/env python3
"""article-writer — vlastní tenký Apify fetch pro deep research.

Fallback, když web_fetch / web_search nedosáhne na obsah: blokovaný web (403,
scrapování, prázdná odpověď) i data ZA SOCIÁLNÍ PLATFORMOU (YouTube přepis,
LinkedIn, X), které běžný web fetch neumí. Volá Apify actory synchronně
(1 HTTP call) a vrací vyčištěný text zdrojů pro dossier.

Zdroje (auto-detekce z inputu, nebo --source):
  web       apify~rag-web-browser            dotaz/URL -> markdown            [default]
  youtube   streamers~youtube-scraper        URL/dotaz -> PŘEPIS + metadata
  linkedin  harvestapi~linkedin-post-search  dotaz -> příspěvky
  x         danek~twitter-scraper            dotaz -> tweety

„API místo shell": čistý urllib wrapper, žádný raw shell / exec. Apify je
pay-per-result -> vždy napřed `--dry-run`. Bez klíče: JSON {"skip":...}, exit 0.

Použití:
  python3 apify_fetch.py "<dotaz nebo URL>" --dry-run
  python3 apify_fetch.py "https://www.youtube.com/watch?v=..." --max 1     # přepis videa
  python3 apify_fetch.py "AI agenti pro malé firmy" --source linkedin --max 5
  python3 apify_fetch.py "li: obchodní AI" --max 5                         # prefix = zdroj

Výstup: JSON list [{source,url,title,text}] na stdout.
"""
import os
import json
import argparse
import urllib.request
import urllib.error

BASE = "https://api.apify.com/v2"
ACTORS = {
    "web":      "apify~rag-web-browser",
    "youtube":  "streamers~youtube-scraper",      # umí přepis: downloadSubtitles + plaintext
    "linkedin": "harvestapi~linkedin-post-search",
    "x":        "danek~twitter-scraper",
}
COST = {"web": 0.005, "youtube": 0.01, "linkedin": 0.01, "x": 0.005}  # orientační $/výsledek
PREFIX = {"yt:": "youtube", "li:": "linkedin", "x:": "x", "web:": "web"}


def _cc_variable(name):
    """Control Center proměnné (Nastavení -> Integrace) — store má přednost před env."""
    try:
        import sys as _sys
        _sys.path.insert(0, "/home/node/.openclaw/cs-skills/_lib")
        from cc_credentials import get_variable  # type: ignore
        return (get_variable(name) or "").strip()
    except Exception:
        return ""

def _token():
    return (_cc_variable("APIFY_API_KEY")
            or os.environ.get("APIFY_API_KEY")
            or os.environ.get("APIFY_TOKEN")
            or os.environ.get("APIFY_API_TOKEN", ""))


def _run(actor, inp, timeout=180):
    """Spustí Apify actor synchronně a vrátí položky datasetu (list) v jednom HTTP callu.

    Token jde v Authorization hlavičce (ne v URL query) — nemůže uniknout přes
    access log / proxy / referrer ani přes URL v tracebacku.
    """
    url = f"{BASE}/acts/{actor}/run-sync-get-dataset-items"
    req = urllib.request.Request(
        url,
        data=json.dumps(inp).encode("utf-8"),
        headers={"Content-Type": "application/json", "Authorization": "Bearer " + _token()},
    )
    try:
        return json.load(urllib.request.urlopen(req, timeout=timeout))
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", "replace")[:300]
        raise RuntimeError(f"Apify {actor} HTTP {e.code}: {body}")


def _fetch_text_url(u, timeout=30, cap=20000):
    """Best-effort stažení titulků, když je actor vrátí jako URL, ne inline.

    Jen http/https — brání čtení lokálních souborů přes file:// z výstupu actoru.
    """
    if not isinstance(u, str) or not u.lower().startswith(("http://", "https://")):
        return ""
    try:
        with urllib.request.urlopen(u, timeout=timeout) as r:
            return r.read().decode("utf-8", "replace")[:cap]
    except Exception:
        return ""


def _is_url(q):
    ql = q.lower()
    return ql.startswith("http://") or ql.startswith("https://")


def detect(q, forced):
    """Vrátí (source, vyčištěný_dotaz) — z --source, prefixu, nebo URL hostu."""
    if forced and forced != "auto":
        return forced, q
    for p, src in PREFIX.items():
        if q.lower().startswith(p):
            return src, q[len(p):].strip()
    ql = q.lower()
    if "youtube.com" in ql or "youtu.be" in ql:
        return "youtube", q
    if "linkedin.com" in ql:
        return "linkedin", q
    if "twitter.com" in ql or "x.com/" in ql:
        return "x", q
    return "web", q


def _input(src, q, n):
    if src == "web":
        return {"query": q, "maxResults": n, "outputFormats": ["markdown"]}
    if src == "youtube":
        common = {"downloadSubtitles": True, "subtitlesFormat": "plaintext",
                  "subtitlesLanguage": "any", "preferAutoGeneratedSubtitles": True}
        if _is_url(q):
            return {**common, "startUrls": [{"url": q}], "maxResults": 1}
        return {**common, "searchQueries": [q], "maxResults": n}
    if src == "linkedin":
        return {"searchQueries": [q], "maxPosts": n, "sortBy": "relevance"}
    if src == "x":
        return {"query": q, "search_type": "Top", "max_posts": n}
    return {"query": q, "maxResults": n}


def _yt_transcript(v):
    """Vrať JEDEN přepis, ne slité jazyky. Reálný tvar (ověřeno na streamers~youtube-scraper):
    subtitles = list dictů {srtUrl, type, language, plaintext}, obvykle víc jazyků.
    Preferuj user_generated (originál) před auto_generated; fallback na popis videa."""
    subs = v.get("subtitles")
    if isinstance(subs, str) and subs.strip():
        return subs
    if isinstance(subs, list):
        def _txt(s):
            t = s.get("plaintext") or s.get("text") or s.get("srt") or ""
            if not t and (s.get("srtUrl") or s.get("url")):
                t = _fetch_text_url(s.get("srtUrl") or s.get("url"))
            return (t or "").strip()
        dicts = [s for s in subs if isinstance(s, dict)]
        for pref in ("user_generated", "auto_generated"):
            for s in dicts:
                if s.get("type") == pref:
                    t = _txt(s)
                    if t:
                        return t
        for s in dicts:
            t = _txt(s)
            if t:
                return t
        for s in subs:
            if isinstance(s, str) and s.strip():
                return s
    return v.get("text") or ""  # fallback: popis videa


def _parse(src, items):
    out = []
    for it in items:
        if not isinstance(it, dict):
            continue
        if src == "web":
            md = it.get("metadata") or {}
            sr = it.get("searchResult") or {}
            crawl = it.get("crawl") or {}
            out.append({"source": "web",
                        "url": md.get("url") or it.get("url") or crawl.get("loadedUrl") or sr.get("url") or "",
                        "title": md.get("title") or sr.get("title") or "",
                        "text": it.get("markdown") or it.get("text") or it.get("content") or ""})
        elif src == "youtube":
            ch = it.get("channelName") or ""
            title = (it.get("title") or "")
            out.append({"source": "youtube",
                        "url": it.get("url") or "",
                        "title": (title + (f" — {ch}" if ch else "")).strip(),
                        "text": _yt_transcript(it)})
        elif src == "linkedin":
            # ověřeno na harvestapi~linkedin-post-search: text=content, url=linkedinUrl, autor=author.name (dict)
            au = it.get("author") or {}
            author = au.get("name") if isinstance(au, dict) else (au or "")
            out.append({"source": "linkedin",
                        "url": it.get("linkedinUrl") or it.get("url") or it.get("postUrl") or "",
                        "title": author or it.get("authorName") or "",
                        "text": it.get("content") or it.get("text") or ""})
        elif src == "x":
            # ověřeno na danek~twitter-scraper: text=text, autor=user_info.name/screen_name, URL neexistuje -> poskládat
            ui = it.get("user_info") or {}
            screen = it.get("screen_name") or (ui.get("screen_name") if isinstance(ui, dict) else "") or ""
            author = (ui.get("name") if isinstance(ui, dict) else "") or screen or it.get("username") or ""
            tid = it.get("tweet_id") or ""
            url = it.get("url") or it.get("twitterUrl") or (f"https://x.com/{screen}/status/{tid}" if screen and tid else "")
            out.append({"source": "x",
                        "url": url,
                        "title": author,
                        "text": it.get("text") or it.get("full_text") or it.get("fullText") or ""})
    return [o for o in out if o.get("text")]


def main():
    ap = argparse.ArgumentParser(
        description="Tenký Apify fetch pro deep research (web + YouTube přepis + LinkedIn + X).")
    ap.add_argument("query", help="dotaz nebo URL (nebo prefix yt:/li:/x:/web:)")
    ap.add_argument("--source", choices=["auto", "web", "youtube", "linkedin", "x"], default="auto")
    ap.add_argument("--max", type=int, default=3, help="max zdrojů (drž nízko kvůli kreditům)")
    ap.add_argument("--dry-run", action="store_true", help="jen odhad ceny, žádné volání API")
    a = ap.parse_args()

    src, q = detect(a.query, a.source)

    if a.dry_run:
        print(json.dumps({
            "dryRun": True, "source": src, "actor": ACTORS[src], "query": q,
            "maxResults": a.max, "estimatedCostUsd": round(a.max * COST.get(src, 0.01), 4),
            "note": "Odhad. Ostrý běh spusť bez --dry-run.",
        }, ensure_ascii=False, indent=2))
        return

    if not _token():
        print(json.dumps({
            "skip": "APIFY_API_KEY není nastavený — research pokračuje bez Apify fallbacku.",
        }, ensure_ascii=False))
        return

    items = _run(ACTORS[src], _input(src, q, a.max))
    print(json.dumps(_parse(src, items), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
